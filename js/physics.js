const norm360 = (a) => ((a % 360) + 360) % 360;

// Interpolación lineal en periodo, saturada en el rango modelado (4 a 10 s).
function enPeriodo(fila, t) {
  const lo = PERIODOS[0];
  const hi = PERIODOS[PERIODOS.length - 1];
  const tp = Math.min(hi, Math.max(lo, Number(t) || lo));
  const w = ((tp - lo) / (hi - lo)) * (PERIODOS.length - 1);
  const i = Math.min(PERIODOS.length - 2, Math.floor(w));
  return fila[i] + (fila[i + 1] - fila[i]) * (w - i);
}

// factorOleaje(id, dirección, periodo) = H_rompiente / H_offshore. La dirección interpola
// entre los dos bins de 10 grados que la rodean, dando la vuelta por 360/0. Devuelve 0 si
// el spot no tiene tabla o si faltan dirección o periodo: sin dato, no se inventa altura.
export function factorOleaje(id, dir, periodo) {
  const tabla = FACTOR[id];
  if (!tabla || dir == null || periodo == null) return 0;
  const d = norm360(Number(dir));
  const paso = DIRS[1] - DIRS[0];
  const i = Math.floor(d / paso) % DIRS.length;
  const w = (d - DIRS[i]) / paso;
  const v0 = enPeriodo(tabla[i], periodo);
  const v1 = enPeriodo(tabla[(i + 1) % DIRS.length], periodo);
  return v0 + (v1 - v0) * w;
}
